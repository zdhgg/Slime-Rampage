/** 计算当前出战小队的职能人数与激活羁绊 */
export function computeSquadSynergies(rosterTypes = []) {
  const counts = { vanguard: 0, striker: 0, support: 0 }
  for (const type of rosterTypes) {
    const def = PET_ROSTER_BY_ID[type]
    if (def && counts[def.role] !== undefined) counts[def.role]++
  }
  const active = []
  if (counts.vanguard >= 2) active.push(SQUAD_SYNERGIES.vanguard)
  if (counts.striker >= 2) active.push(SQUAD_SYNERGIES.striker)
  if (counts.support >= 2) active.push(SQUAD_SYNERGIES.support)
  if (counts.vanguard >= 1 && counts.striker >= 1 && counts.support >= 1) {
    active.push(SQUAD_SYNERGIES.balanced)
  }
  const vanguardActive = counts.vanguard >= 2
  const strikerActive = counts.striker >= 2
  const supportActive = counts.support >= 2
  const balancedActive = counts.vanguard >= 1 && counts.striker >= 1 && counts.support >= 1
  return {
    counts,
    active,
    vanguardActive,
    strikerActive,
    supportActive,
    balancedActive,
    aoeMul: vanguardActive ? 1.25 : 1,
    recoveryCut: vanguardActive ? 2 : 0,
    shieldMul: vanguardActive ? 1.25 : 1,
    critBonus: strikerActive ? 0.12 : 0,
    strikerExtraTarget: strikerActive ? 1 : 0,
    strikerBlastMul: strikerActive ? 1.2 : 1,
    zoneMul: supportActive ? 1.25 : 1,
    controlVulnBonus: supportActive ? 0.15 : 0,
    activeCdMul: balancedActive ? 0.85 : 1,
    hasteBonus: balancedActive ? 0.15 : 0,
  }
}
